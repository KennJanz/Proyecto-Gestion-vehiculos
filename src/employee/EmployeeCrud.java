    private void loadTable() {
        ArrayList<Employee> empleados = list.getList();
        model.setRowCount(0);
        for (Employee emp : empleados) {
            Object[] data = {
                emp.getId(),
                emp.getName(),
                emp.getPosition(),
                emp.getPhone(),
                emp.getEmail(),
                UtilDate.toString(emp.getBirthDate()),
                emp.getSalary()
            };
            model.addRow(data);
        }
    }

