    private void txtFilterActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_txtFilterActionPerformed
        String text = txtFilter.getText();
        if (text.trim().length() == 0) {
            sorter.setRowFilter(null);
        } else {
            // (?i) para ignorar mayúsculas/minúsculas
            sorter.setRowFilter(RowFilter.regexFilter("(?i)" + text));
        }
    }//GEN-LAST:event_txtFilterActionPerformed

    private void btnAcceptActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAcceptActionPerformed
        int row = tblEmployees.getSelectedRow();
        if (row == -1) {
            UtilGui.showErrorMessage(this, "Debe seleccionar un empleado", "Error");
            return;
        }

        // convertimos la fila de la vista a la fila del modelo
        int modelRow = tblEmployees.convertRowIndexToModel(row);

        // buscamos el objeto Employee correspondiente en el ArrayList
        String id = model.getValueAt(modelRow, 0).toString(); // columna 0 = ID
        employee = list.find(id);  

        setVisible(false);
        this.dispose();
    }//GEN-LAST:event_btnAcceptActionPerformed

