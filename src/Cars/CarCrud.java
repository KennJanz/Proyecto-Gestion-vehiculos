    private void loadTable(){
     HashMap<String, Car> map = list.getMap();
        model.setRowCount(0);
        for (Car car : map.values()) {
            Object[] data = {car.getLicensePlate(), car.getBrand(),car.getModel(), String.valueOf(car.getYear().getValue()),car.getCarType(),car.getCarState()};
            model.addRow(data);
        }   
    }
    
    
    
    

